#!/usr/bin/env python3
"""Generate firmware/mcu/src/generated.h from the host code, so the firmware and the host share
one definition of: control actions, modes, motion limits and pen timing (comlang/engine.py,
comlang/protocol.py), and the display font (rendered once from DejaVu Sans Mono Bold).

    python3 tools/gen_firmware_tables.py          # rewrite the header
    python3 tools/gen_firmware_tables.py --check  # exit 1 if it is out of date (tests/test_sync.py)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from comlang import engine, protocol          # noqa: E402

OUT = os.path.join(ROOT, "firmware", "mcu", "src", "generated.h")
FONT_TTF = "/usr/share/fonts/TTF/DejaVuSansMono-Bold.ttf"
FONT_W, FONT_H, FONT_PX, FONT_TOP = 8, 13, 13, 3     # cell size, render size, first row used


def font_rows():
    """ASCII 32..126 as FONT_H rows of 8-bit masks (bit 7 = left), or None without the font."""
    try:
        from PIL import Image, ImageDraw, ImageFont
        f = ImageFont.truetype(FONT_TTF, FONT_PX)
    except Exception:
        return None
    out = []
    for c in range(32, 127):
        im = Image.new("L", (FONT_W, FONT_H + FONT_TOP + 4))
        d = ImageDraw.Draw(im)
        d.fontmode = "1"
        d.text((0, 0), chr(c), font=f, fill=255)
        out.append([sum(0x80 >> x for x in range(FONT_W) if im.getpixel((x, y + FONT_TOP)) > 127)
                    for y in range(FONT_H)])
    return out


def render(font):
    L = ["/* GENERATED by tools/gen_firmware_tables.py from comlang/engine.py and comlang/protocol.py.",
         "   Do not edit: change the Python and re-run the tool. tests/test_sync.py checks it. */",
         "#pragma once", "#include <stdint.h>", ""]
    L.append("/* control actions reported to the host as 'E <action>' (protocol.ACTIONS) */")
    for i, a in enumerate(protocol.ACTIONS):
        L.append("#define ACT_%s %d" % (a.upper(), i))
    L.append("#define ACT_COUNT %d" % len(protocol.ACTIONS))
    L.append("static const char *const ACTION_NAME[ACT_COUNT] __attribute__((unused)) = {%s};" %
             ", ".join('"%s"' % a for a in protocol.ACTIONS))
    L.append("")
    L.append("/* output modes shown on the speaker display (protocol.MODES / MODE_NAME) */")
    L.append("#define MODE_COUNT %d" % len(protocol.MODES))
    L.append("static const char *const MODE_KEY[MODE_COUNT] __attribute__((unused)) = {%s};" %
             ", ".join('"%s"' % m for m in protocol.MODES))
    L.append("static const char *const MODE_LABEL[MODE_COUNT] __attribute__((unused)) = {%s};" %
             ", ".join('"%s"' % protocol.MODE_NAME[m] for m in protocol.MODES))
    L.append("")
    L.append("/* motion limits and pen timing (comlang/engine.py) */")
    for name, val in (("WORKSPACE_MM", engine.WORKSPACE), ("V_WRITE_MM_S", engine.V_WRITE),
                      ("V_TRAVEL_MM_S", engine.V_TRAVEL), ("ACCEL_MM_S2", engine.ACCEL),
                      ("T_PEN_S", engine.T_PEN)):
        L.append("#define GEN_%s %.4ff" % (name, val))
    L.append("")
    if font:
        L.append("/* display font: ASCII 32..126, %dx%d px, one byte per row, bit 7 = left */" % (FONT_W, FONT_H))
        L.append("#define FONT_W %d\n#define FONT_H %d" % (FONT_W, FONT_H))
        L.append("static const uint8_t FONT[95][FONT_H] __attribute__((unused)) = {")
        for c, rows in zip(range(32, 127), font):
            L.append("    {%s}, /* %r */" % (", ".join("0x%02x" % r for r in rows), chr(c)))
        L.append("};")
    return "\n".join(L) + "\n"


def main():
    font = font_rows()
    if font is None:                       # keep the committed font if the TTF is not installed
        old = open(OUT).read() if os.path.exists(OUT) else ""
        i = old.find("/* display font")
        text = render(None) + (old[i:] if i >= 0 else "")
    else:
        text = render(font)
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text
        print("generated.h up to date" if ok else "generated.h OUT OF DATE: run tools/gen_firmware_tables.py")
        return 0 if ok else 1
    open(OUT, "w").write(text)
    print("wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
